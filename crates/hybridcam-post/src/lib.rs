//! Configurable G-code Post-Processor engine for GRBL, Mach3/4, LinuxCNC, Masso, and Fanuc/ISO.

use hybridcam_cam::{MotionKind, Toolpath};
use hybridcam_geom::Units;
use serde::{Deserialize, Serialize};
use std::fmt::Write;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum PostDialect {
    Grbl,
    Marlin,
    Mach34,
    LinuxCnc,
    Masso,
    FanucIso,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PostConfig {
    pub dialect: PostDialect,
    pub units: Units,
    pub safe_z_mm: f64,
    pub emit_tool_change_m6: bool,
    pub program_name: String,
}

impl Default for PostConfig {
    fn default() -> Self {
        Self {
            dialect: PostDialect::Grbl,
            units: Units::Millimeters,
            safe_z_mm: 15.0,
            emit_tool_change_m6: true,
            program_name: "HybridCAM_Job".into(),
        }
    }
}

/// Render a list of `Toolpath`s into machine-ready G-code.
pub fn post_process(toolpaths: &[Toolpath], config: &PostConfig) -> String {
    let mut out = String::with_capacity(8192);
    let is_marlin = config.dialect == PostDialect::Marlin;
    let unit_code = match config.units {
        Units::Millimeters => "G21",
        Units::Inches => "G20",
    };

    if is_marlin {
        let _ = writeln!(out, "; {} - Generated by HybridCAM (Marlin/MPCNC)", config.program_name);
        let _ = writeln!(out, "G90");
    } else {
        let _ = writeln!(out, "( {} - Generated by HybridCAM )", config.program_name);
        let _ = writeln!(out, "G90 G94 G17");
    }
    let _ = writeln!(out, "{unit_code}");
    let safe_z = config.units.from_mm(config.safe_z_mm);
    if is_marlin {
        let _ = writeln!(out, "G0 Z{safe_z:.3} F900");
    } else {
        let _ = writeln!(out, "G0 Z{safe_z:.3}");
    }

    let mut current_tool: Option<u32> = None;

    for tp in toolpaths {
        if current_tool != Some(tp.tool_number) {
            if current_tool.is_some() {
                let _ = writeln!(out, "M5");
                let _ = writeln!(out, "G0 Z{safe_z:.3}");
            }
            if is_marlin {
                let _ = writeln!(out, "; Tool T{}", tp.tool_number);
            } else if config.emit_tool_change_m6 && config.dialect != PostDialect::Grbl {
                let _ = writeln!(out, "T{} M6", tp.tool_number);
            } else {
                let _ = writeln!(out, "( Tool T{} )", tp.tool_number);
            }
            let _ = writeln!(out, "M3 S{}", tp.spindle_rpm);
            current_tool = Some(tp.tool_number);
        }

        let mut last_feed: Option<f64> = None;
        for seg in &tp.segments {
            let x = config.units.from_mm(seg.end.x);
            let y = config.units.from_mm(seg.end.y);
            let z = config.units.from_mm(seg.end.z);

            match seg.kind {
                MotionKind::Rapid => {
                    if is_marlin {
                        let _ = writeln!(out, "G0 X{x:.3} Y{y:.3} Z{z:.3} F3000");
                    } else {
                        let _ = writeln!(out, "G0 X{x:.3} Y{y:.3} Z{z:.3}");
                    }
                }
                MotionKind::Linear => {
                    let feed = config.units.from_mm(seg.feed_mm_min);
                    if last_feed.map(|f| (f - feed).abs() > 0.5).unwrap_or(true) {
                        let _ = writeln!(out, "G1 X{x:.3} Y{y:.3} Z{z:.3} F{feed:.1}");
                        last_feed = Some(feed);
                    } else {
                        let _ = writeln!(out, "G1 X{x:.3} Y{y:.3} Z{z:.3}");
                    }
                }
                MotionKind::ArcCW | MotionKind::ArcCCW => {
                    let g = if seg.kind == MotionKind::ArcCW { "G2" } else { "G3" };
                    let (i, j) = seg.arc_center_xy.unwrap_or((0.0, 0.0));
                    let iu = config.units.from_mm(i);
                    let ju = config.units.from_mm(j);
                    let _ = writeln!(out, "{g} X{x:.3} Y{y:.3} I{iu:.3} J{ju:.3}");
                }
            }
        }
    }

    let _ = writeln!(out, "M5");
    let _ = writeln!(out, "G0 Z{safe_z:.3}");
    if !is_marlin {
        let _ = writeln!(out, "M30");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use hybridcam_cam::{MotionSegment, Toolpath};
    use hybridcam_geom::Point3;
    use uuid::Uuid;

    #[test]
    fn test_grbl_header_and_footer() {
        let tp = Toolpath {
            operation_id: Uuid::new_v4(),
            tool_number: 1,
            spindle_rpm: 18000,
            segments: vec![MotionSegment {
                kind: MotionKind::Linear,
                start: Point3::new(0.0, 0.0, 0.0),
                end: Point3::new(10.0, 0.0, -2.0),
                arc_center_xy: None,
                feed_mm_min: 1500.0,
            }],
            estimated_time_sec: 1.0,
            total_cut_distance_mm: 10.0,
            warnings: vec![],
        };
        let gcode = post_process(&[tp], &PostConfig::default());
        assert!(gcode.contains("G21"));
        assert!(gcode.contains("M3 S18000"));
        assert!(gcode.contains("G1 X10.000 Y0.000 Z-2.000 F1500.0"));
        assert!(gcode.ends_with("M30\n") || gcode.ends_with("M30\r\n"));
    }

    #[test]
    fn test_marlin_mpcnc_dialect() {
        let tp = Toolpath {
            operation_id: Uuid::new_v4(),
            tool_number: 1,
            spindle_rpm: 18000,
            segments: vec![MotionSegment {
                kind: MotionKind::Rapid,
                start: Point3::new(0.0, 0.0, 15.0),
                end: Point3::new(5.0, 5.0, 5.0),
                arc_center_xy: None,
                feed_mm_min: 0.0,
            }],
            estimated_time_sec: 1.0,
            total_cut_distance_mm: 0.0,
            warnings: vec![],
        };
        let cfg = PostConfig {
            dialect: PostDialect::Marlin,
            ..PostConfig::default()
        };
        let gcode = post_process(&[tp], &cfg);
        assert!(gcode.starts_with("; HybridCAM_Job"));
        assert!(!gcode.contains("M30"));
        assert!(gcode.contains("G0 X5.000 Y5.000 Z5.000 F3000"));
    }
}
